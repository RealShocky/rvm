//! Cross-repo receipt anchoring for the RVM witness chain (ADR-156).
//!
//! Consumes the witness/receipt contract extracted from ruflo ADR-322C
//! (`ruflo` `v3/docs/spec/witness-receipt-contract.md`, tracked by
//! `ruvnet/ruflo#3066` / `ruvnet/rvm#35`): verifies a
//! `ruflo.flywheel-receipt/v1` evaluation receipt end to end —
//! JCS canonicalization, SHA-256 content IDs, Ed25519 over
//! domain-prefixed bytes, statistical recomputation — and anchors a
//! commitment to it as an ADR-134 witness record.
//!
//! # What is contract and what is proposal
//!
//! - The **receipt** format, its verification algorithm, and the signing
//!   domain `ruflo/flywheel-receipt/v1` are ADR-322C contract. ADR-322C
//!   defines exactly **two** Ed25519 signing domains — the receipt domain
//!   and `ruflo/flywheel-ledger-head/v1` (specified, unimplemented on
//!   ruflo `main`) — which is why this crate anchors the *receipt* and
//!   not the ledger head (contract gap G2; checklist C3).
//! - The **anchor record** (`ruflo.anchor-record/v1`), its
//!   `assuranceLevel` field, and the `ruflo/flywheel-anchor/v1` domain
//!   are a **`PROPOSED-EXTENSION`** (contract §9): a PIR proposal pending
//!   ruflo review, not an established contract. Code in [`anchor`] says
//!   so at every surface.
//!
//! # Version policy
//!
//! Pins are **`schemaVersion` + `gateVersion` strings**
//! ([`receipt::SUPPORTED_SCHEMA_VERSION`],
//! [`receipt::SUPPORTED_GATE_VERSION`]), never ruflo git SHAs — a SHA pin
//! would couple this repo's release cadence to ruflo's commit history
//! (checklist F1). Unrecognized versions are refused, never best-effort
//! parsed (F2), and a gate change is never applied retroactively (F3):
//! this verifier refuses receipts under gates it cannot recompute.
//!
//! # Assurance honesty (ADR-285)
//!
//! Receipts are service-side artifacts. Anchoring one into the
//! hypervisor-side witness chain records provenance; it does **not**
//! confer hypervisor guarantees. [`anchor::anchor_verified_receipt`]
//! stamps `service-side` unconditionally — there is no parameter through
//! which a caller could claim otherwise for a foreign record.
//!
//! # `no_std`
//!
//! `no_std` with `alloc`: receipts are JSON documents, so parsing and
//! canonicalization allocate. Ed25519 verification uses the same
//! `ed25519-dalek` (default-features off) already trusted by `rvm-rvf`.

